// Development-only DOM behavior test. No browser, resource loading, or network access.
// Usage: NODE_PATH=/path/to/dev/node_modules node tests/report-interactions.cjs report.html
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM, VirtualConsole } = require('jsdom');
const html = fs.readFileSync(process.argv[2], 'utf8');
const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', e => { if (!e.message.includes('Could not parse CSS')) errors.push(e.message); });
const dom = new JSDOM(html, { runScripts: 'outside-only', virtualConsole });
const { window } = dom;
const { document } = window;
for (const api of ['fetch', 'XMLHttpRequest', 'WebSocket']) {
  window[api] = function () { throw new Error('Unexpected outbound API: ' + api); };
}
window.HTMLElement.prototype.scrollIntoView = function () {};
const scripts = [...document.querySelectorAll('script')];
assert.equal(scripts.length, 1, 'one trusted bundled interaction script');
assert.equal(scripts[0].src, '', 'no external script source');
assert.equal(window.getComputedStyle(document.querySelector('.inventory-toolbar')).display, 'none', 'inventory search stays hidden without JavaScript');
window.eval(scripts[0].textContent);
assert.equal(window.getComputedStyle(document.querySelector('.inventory-toolbar')).display, 'flex', 'inventory search appears when the local script is active');
const cards = [...document.querySelectorAll('.finding')];
const visible = () => cards.filter(card => !card.hidden);
assert.ok(cards.length > 0, 'synthetic preview contains findings');
assert.equal(visible().length, cards.length);
const priority = ['critical', 'high', 'medium', 'low', 'info'].find(value => {
  const count = cards.filter(card => card.dataset.severity === value).length;
  return count > 0 && count < cards.length;
});
assert.ok(priority, 'fixture contains at least two finding priorities');
const priorityFilter = document.querySelector(`[data-filter="${priority}"]`);
priorityFilter.click();
assert.ok(visible().length > 0, 'selected priority has visible findings');
assert.ok(visible().every(card => card.dataset.severity === priority));
assert.equal(priorityFilter.getAttribute('aria-pressed'), 'true');
const search = document.getElementById('finding-search');
search.value = 'a-term-with-no-matches-in-the-fixture';
search.dispatchEvent(new window.Event('input', { bubbles: true }));
assert.equal(visible().length, 0);
assert.equal(document.getElementById('no-results').hidden, false);
assert.match(document.getElementById('filter-status').textContent, /^Showing 0 of /);
document.getElementById('clear-filters').click();
assert.equal(visible().length, cards.length);
assert.equal(search.value, '');
assert.equal(document.activeElement, search);
const expand = document.getElementById('expand-evidence');
expand.click();
assert.ok(visible().every(card => card.querySelector('.finding-evidence').open));
assert.match(expand.textContent, /Collapse/);
priorityFilter.click();
assert.match(expand.textContent, /Collapse/, 'control should describe the next action after filtering expanded findings');
expand.click();
assert.ok(visible().every(card => !card.querySelector('.finding-evidence').open));
assert.match(expand.textContent, /Expand/);
const previouslyHidden = cards.find(card => card.hidden);
assert.ok(previouslyHidden, 'fixture has another priority');
window.location.hash = previouslyHidden.id;
window.dispatchEvent(new window.Event('hashchange'));
assert.equal(previouslyHidden.hidden, false, 'anchors reveal a filtered finding');
assert.equal(visible().length, cards.length);
const inventoryGroups = [...document.querySelectorAll('.inventory-group')];
const inventoryRows = [...document.querySelectorAll('.inventory-row')];
const visibleInventory = () => inventoryRows.filter(row => !row.hidden);
assert.ok(inventoryRows.length > 0, 'fixture contains named inventory');
assert.ok(inventoryGroups.every(group => !/\d+ enabled|\d+ disabled|\d+ unknown/.test(group.querySelector(':scope > summary').textContent)));
assert.ok(!document.getElementById('inventory').textContent.includes('State unknown'));
const inventorySearch = document.getElementById('inventory-search');
const inventoryStatus = document.getElementById('inventory-search-status');
const initialGroups = inventoryGroups.map(group => group.open);
const name = inventoryRows[0].querySelector('.inventory-item-name strong').textContent;
inventorySearch.value = name;
inventorySearch.dispatchEvent(new window.Event('input', { bubbles: true }));
assert.ok(visibleInventory().length > 0, 'actual inventory name is searchable');
assert.ok(visibleInventory().every(row => row.textContent.toLocaleLowerCase().includes(name.toLocaleLowerCase())));
assert.ok(inventoryGroups.filter(group => !group.hidden).every(group => group.open), 'matching inventory groups open automatically');
assert.equal(inventoryStatus.textContent, `${visibleInventory().length} of ${inventoryRows.length} items`);
inventorySearch.value = 'a-term-with-no-inventory-matches-in-the-fixture';
inventorySearch.dispatchEvent(new window.Event('input', { bubbles: true }));
assert.equal(visibleInventory().length, 0);
assert.equal(document.getElementById('inventory-no-results').hidden, false);
document.getElementById('clear-inventory-search').click();
assert.equal(visibleInventory().length, inventoryRows.length);
assert.equal(inventorySearch.value, '');
assert.equal(document.activeElement, inventorySearch);
assert.deepEqual(inventoryGroups.map(group => group.open), initialGroups, 'clearing inventory search restores disclosures');
inventorySearch.value = 'a-term-with-no-inventory-matches-in-the-fixture';
inventorySearch.dispatchEvent(new window.Event('input', { bubbles: true }));
window.location.hash = inventoryGroups[0].id;
window.dispatchEvent(new window.Event('hashchange'));
assert.equal(inventorySearch.value, '', 'inventory anchors clear an obstructing search');
assert.equal(inventoryGroups[0].hidden, false);
assert.equal(inventoryGroups[0].open, true);
assert.equal(visibleInventory().length, inventoryRows.length);
inventorySearch.value = name;
inventorySearch.dispatchEvent(new window.Event('input', { bubbles: true }));
const inventoryCounts = [...document.querySelectorAll('.inventory-count')];
const countsBefore = inventoryCounts.map(count => count.textContent);
const before = [...document.querySelectorAll('details')].map(detail => detail.open);
window.dispatchEvent(new window.Event('beforeprint'));
assert.ok([...document.querySelectorAll('details')].every(detail => detail.open));
assert.ok(inventoryCounts.every(count => count.textContent === count.dataset.total), 'print uses complete inventory counts');
window.dispatchEvent(new window.Event('afterprint'));
assert.deepEqual([...document.querySelectorAll('details')].map(detail => detail.open), before);
assert.deepEqual(inventoryCounts.map(count => count.textContent), countsBefore, 'print restores filtered inventory counts');
assert.equal(inventorySearch.value, name, 'print preserves the inventory query');
assert.deepEqual(errors, []);
console.log('PASS: finding filters, named inventory search, reset/focus, disclosures, anchor reveal, print state, and no outbound APIs.');
dom.window.close();
